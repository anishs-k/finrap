import { type FormEvent, useCallback, useEffect, useState } from "react";
import { Eye, FileDown, FileJson2, Plus, Search, X } from "lucide-react";
import { api, type TuJsonPdfDocument, type UserAccount } from "../api/client";
import "../styles/tu-json-pdf.css";

type Props = {
  user: UserAccount;
  canGenerate: boolean;
};

const EMPTY_PAGINATION = { page: 1, limit: 10, total: 0, totalPages: 1 };
const EMPTY_FORM = {
  firstName: "",
  lastName: "",
  mobileNumber: "",
  panNumber: "",
  consentAccepted: false
};

export function TuJsonPdfView({ user, canGenerate }: Props) {
  const [documents, setDocuments] = useState<TuJsonPdfDocument[]>([]);
  const [pagination, setPagination] = useState(EMPTY_PAGINATION);
  const [page, setPage] = useState(1);
  const [search, setSearch] = useState("");
  const [modalOpen, setModalOpen] = useState(false);
  const [form, setForm] = useState(EMPTY_FORM);
  const [loading, setLoading] = useState(true);
  const [generating, setGenerating] = useState(false);
  const [error, setError] = useState("");

  const loadDocuments = useCallback(async () => {
    setLoading(true);
    setError("");
    try {
      const response = await api.tuJsonPdfDocuments({ page, limit: 10, search: search.trim() || undefined });
      setDocuments(response.items);
      setPagination(response.pagination);
    } catch (requestError) {
      setError(messageFor(requestError));
    } finally {
      setLoading(false);
    }
  }, [page, search]);

  useEffect(() => {
    const timer = window.setTimeout(loadDocuments, search ? 300 : 0);
    return () => window.clearTimeout(timer);
  }, [loadDocuments, search]);

  function openModal() {
    setForm(EMPTY_FORM);
    setError("");
    setModalOpen(true);
  }

  async function generate(event: FormEvent) {
    event.preventDefault();
    setError("");

    setGenerating(true);
    try {
      const generated = await api.generateTuJsonPdf(form);
      setModalOpen(false);
      setPage(1);
      setDocuments((current) => [generated, ...current.filter((entry) => entry.id !== generated.id)].slice(0, 10));
      await viewDocument(generated);
    } catch (requestError) {
      setError(messageFor(requestError));
    } finally {
      setGenerating(false);
    }
  }

  async function viewDocument(document: TuJsonPdfDocument) {
    setError("");
    try {
      const blob = await api.tuJsonPdfFile(document.id);
      const url = URL.createObjectURL(blob);
      window.open(url, "_blank");
      window.setTimeout(() => URL.revokeObjectURL(url), 60_000);
    } catch (requestError) {
      setError(messageFor(requestError));
    }
  }

  async function downloadDocument(document: TuJsonPdfDocument) {
    setError("");
    try {
      const blob = await api.tuJsonPdfFile(document.id, true);
      const url = URL.createObjectURL(blob);
      const anchor = window.document.createElement("a");
      anchor.href = url;
      anchor.download = document.fileName;
      anchor.click();
      window.setTimeout(() => URL.revokeObjectURL(url), 5_000);
    } catch (requestError) {
      setError(messageFor(requestError));
    }
  }

  return (
    <div className="view-stack tu-json-pdf-view">
      <section className="page-heading">
        <div>
          <p className="eyebrow">- Bureau Utility</p>
          <h1>TU JSON to PDF</h1>
          <p>Generate a structured TransUnion CIBIL PDF using the integrated TU JSON provider.</p>
        </div>
        {canGenerate && (
          <button className="primary-button" type="button" onClick={openModal}>
            <Plus size={18} />
            Generate PDF
          </button>
        )}
      </section>

      <section className="tu-json-pdf-panel">
        <div className="tu-json-pdf-toolbar">
          <label className="tu-json-pdf-search">
            <Search size={21} />
            <input
              type="search"
              value={search}
              onChange={(event) => {
                setSearch(event.target.value);
                setPage(1);
              }}
              placeholder="Search customer, control number, generated by..."
            />
          </label>
        </div>

        {error && <p className="form-error tu-json-pdf-error">{error}</p>}
        {loading ? (
          <div className="tu-json-pdf-empty">Loading generated reports...</div>
        ) : documents.length === 0 ? (
          <div className="tu-json-pdf-empty">
            <FileJson2 size={32} />
            <strong>No generated reports</strong>
            <span>Generate a TU report to create the first PDF record.</span>
          </div>
        ) : (
          <div className="tu-json-pdf-table-wrap">
            <table className="tu-json-pdf-table">
              <thead>
                <tr>
                  <th>Customer</th>
                  <th>Score</th>
                  <th>Accounts</th>
                  <th>Enquiries</th>
                  <th>Generated By</th>
                  <th>Created</th>
                  <th>Action</th>
                </tr>
              </thead>
              <tbody>
                {documents.map((document) => (
                  <tr key={document.id}>
                    <td data-label="Customer">
                      <strong>{document.customerName}</strong>
                      <small>{document.controlNumber || "-"}</small>
                    </td>
                    <td data-label="Score">{document.score ?? "-"}</td>
                    <td data-label="Accounts">{document.accountCount}</td>
                    <td data-label="Enquiries">{document.inquiryCount}</td>
                    <td data-label="Generated By">
                      <strong>{document.actorName || (document.actorId === user.id ? user.name : "-")}</strong>
                      <small>{document.actorEmail || "-"}</small>
                    </td>
                    <td data-label="Created">{formatDate(document.createdAt)}</td>
                    <td data-label="Action">
                      <div className="tu-json-pdf-actions">
                        <button type="button" className="tu-json-pdf-action secondary" onClick={() => viewDocument(document)}>
                          <Eye size={16} />
                          View
                        </button>
                        <button type="button" className="tu-json-pdf-action" onClick={() => downloadDocument(document)}>
                          <FileDown size={16} />
                          Download
                        </button>
                      </div>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}

        {pagination.totalPages > 1 && (
          <div className="tu-json-pdf-pagination">
            <button type="button" disabled={page <= 1} onClick={() => setPage((value) => Math.max(1, value - 1))}>
              Previous
            </button>
            <span>Page {pagination.page} of {pagination.totalPages}</span>
            <button type="button" disabled={page >= pagination.totalPages} onClick={() => setPage((value) => Math.min(pagination.totalPages, value + 1))}>
              Next
            </button>
          </div>
        )}
      </section>

      {modalOpen && (
        <div className="tu-json-pdf-modal-backdrop" role="presentation">
          <section className="tu-json-pdf-modal" role="dialog" aria-modal="true" aria-labelledby="tu-json-pdf-modal-title">
            <header>
              <div>
                <p className="eyebrow">- Generate Report</p>
                <h2 id="tu-json-pdf-modal-title">Generate TU CIBIL PDF</h2>
              </div>
              <button type="button" aria-label="Close" onClick={() => setModalOpen(false)}>
                <X size={23} />
              </button>
            </header>
            <form onSubmit={generate}>
              <div className="tu-json-pdf-form-grid">
                <label>
                  <span>First Name</span>
                  <input
                    required
                    value={form.firstName}
                    onChange={(event) => setForm((current) => ({ ...current, firstName: event.target.value }))}
                    placeholder="Akshat"
                  />
                </label>
                <label>
                  <span>Last Name</span>
                  <input
                    required
                    value={form.lastName}
                    onChange={(event) => setForm((current) => ({ ...current, lastName: event.target.value }))}
                    placeholder="Dangi"
                  />
                </label>
                <label>
                  <span>Mobile Number</span>
                  <input
                    required
                    inputMode="numeric"
                    maxLength={10}
                    pattern="[0-9]{10}"
                    value={form.mobileNumber}
                    onChange={(event) =>
                      setForm((current) => ({
                        ...current,
                        mobileNumber: event.target.value.replace(/\D/g, "").slice(0, 10)
                      }))
                    }
                    placeholder="9876543210"
                  />
                </label>
                <label>
                  <span>PAN Number</span>
                  <input
                    required
                    maxLength={10}
                    pattern="[A-Za-z]{5}[0-9]{4}[A-Za-z]"
                    value={form.panNumber}
                    onChange={(event) =>
                      setForm((current) => ({
                        ...current,
                        panNumber: event.target.value.replace(/[^a-zA-Z0-9]/g, "").toUpperCase().slice(0, 10)
                      }))
                    }
                    placeholder="ABCDE1234F"
                  />
                </label>
                <label className="tu-json-pdf-consent">
                  <input
                    required
                    type="checkbox"
                    checked={form.consentAccepted}
                    onChange={(event) =>
                      setForm((current) => ({ ...current, consentAccepted: event.target.checked }))
                    }
                  />
                  <span>I confirm that the customer has consented to fetching their TransUnion CIBIL report.</span>
                </label>
              </div>
              {error && <p className="form-error">{error}</p>}
              <button className="primary-button" type="submit" disabled={generating}>
                {generating ? <span className="button-loader" /> : <FileDown size={18} />}
                {generating ? "Generating report..." : "Generate PDF"}
              </button>
            </form>
          </section>
        </div>
      )}
    </div>
  );
}

function formatDate(value: string | null) {
  if (!value) return "-";
  return new Intl.DateTimeFormat("en-IN", { day: "2-digit", month: "short", year: "numeric" }).format(new Date(value));
}

function messageFor(error: unknown) {
  return error instanceof Error ? error.message : "Request failed. Please try again.";
}
