export function sanitizePermissions(permissions, role) {
  const defaults = ROLE_DEFAULT_PERMISSIONS[role] || [];
  const allowed = new Set(PERMISSIONS);
  const requested = Array.isArray(permissions) ? permissions : defaults;
  return [...new Set(requested.filter((permission) => allowed.has(permission)))];
}

export function hasPublicApiPermission(permissions = []) {
  return permissions.some((permission) => PUBLIC_API_PERMISSIONS.includes(permission));
}
